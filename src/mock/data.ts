export const mockLockers: Locker[] = (() => {
  const result: Locker[] = [];
  const floors = ["F1", "F2"];
  const areas = ["A区", "B区", "C区"];
  mockZones.forEach((zone, zi) => {
    const lockerCount = zone.totalLockers;
    for (let i = 0; i < lockerCount; i++) {
      const floor = floors[Math.floor(i / (lockerCount / floors.length)) % 2];
      const area = areas[i % 3];
      const zoneIndex = zi + 1;
      const rowCode = String.fromCharCode(65 + (i % 6));
      const colCode = String(i % 20).padStart(2, "0");
      const rand = Math.random();
      let status: Locker["status"];
      if (zone.status === "maintenance") {
        status = "fault";
      } else if (rand < 0.72) {
        status = "occupied";
      } else if (rand < 0.85) {
        status = "free";
      } else if (rand < 0.92) {
        status = "cleaning";
      } else if (rand < 0.96) {
        status = "reserved";
      } else {
        status = "fault";
      }
      const sizes: Locker["size"][] = ["S", "M", "L"];
      result.push({
        id: `locker-${zoneIndex}-${i}`,
        zoneId: zone.id,
        code: `${zoneIndex}${rowCode}${colCode}`,
        size: sizes[i % 3],
        status,
        floor,
        area,
        occupiedAt:
          status === "occupied"
            ? new Date(Date.now() - Math.random() * 8 * 3600 * 1000).toISOString()
            : undefined,
      });
    }
  });

  const now = Date.now();
  const pendingOrders: Array<{ id: string; lockerIds: string[]; checkedInAt: string; status: OrderStatus }> = [];
  mockOrders.forEach((o) => {
    if (o.status !== "picked" && o.status !== "refunded") {
      pendingOrders.push({ id: o.id, lockerIds: o.lockerIds, checkedInAt: o.checkedInAt, status: o.status });
    }
  });
  pendingOrders.forEach((po) => {
    po.lockerIds.forEach((lid) => {
      const locker = result.find((l) => l.id === lid);
      if (locker) {
        locker.status = "occupied";
        locker.currentOrderId = po.id;
        locker.occupiedAt = po.checkedInAt;
      }
    });
  });
  return result;
})();

